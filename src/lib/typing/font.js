/** strokes for a legend centred on (0,0), `size` units tall: [along the row, toward the typist] */
export function legendStrokes(text, size) {
  const s = size / 6, adv = 5.6 * s, w = text.length * adv - 1.6 * s;
  const out = [];
  [...text].forEach((ch, i) => {
    for (const pl of FONT[ch] || []) out.push(pl.map(([gx, gy]) => [-w / 2 + i * adv + gx * s, (gy - 3) * s]));
  });
  return out;
}
